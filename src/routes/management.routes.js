const express = require('express');
const adminController = require('../controllers/admin.controller');
const gameController = require('../controllers/game.controller');
const tournamentController = require('../controllers/management.controller');
const financeController = require('../controllers/finance.controller');
const { requireRole } = require('../middleware/auth.middleware');
const talentController = require('../controllers/talent.controller');
const operationsController = require('../controllers/operations.controller');
const physicalController = require('../controllers/physical-tournament.controller');
const officialController = require('../controllers/official.controller');
const { imageUpload } = require('../middleware/upload.middleware');
const liveController = require('../controllers/live-stream.controller');

const router = express.Router();
const managersOnly = requireRole('SUPER_ADMIN', 'TOURNAMENT_MANAGER');
const financeOnly = requireRole('SUPER_ADMIN', 'TOURNAMENT_MANAGER', 'FINANCE_OFFICER');
router.get('/scouting', requireRole('SCOUT', 'TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.scouting);
router.post('/scouting/evaluations', requireRole('SCOUT', 'TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.evaluate);
router.post('/scouting/decisions', requireRole('SCOUT', 'TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.decide);
router.get('/teams', requireRole('TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.teams);
router.post('/teams', requireRole('TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.createTeam);
router.post('/teams/:id/members', requireRole('TOURNAMENT_MANAGER', 'SUPER_ADMIN'), talentController.addMember);

router.get('/payments', financeOnly, financeController.index);
router.get('/live', managersOnly, liveController.adminIndex);
router.post('/payments/:id/refund', financeOnly, financeController.refund);
router.post('/payments/:id/verify-bank-transfer', financeOnly, financeController.verifyBankTransfer);
router.get('/users', requireRole('SUPER_ADMIN'), operationsController.users);
router.post('/users/:id/:action', requireRole('SUPER_ADMIN'), operationsController.updateUserAccount);
router.get('/users/officials/new', requireRole('SUPER_ADMIN'), officialController.newOfficial);
router.post('/users/officials', requireRole('SUPER_ADMIN'), officialController.createOfficial);
router.get('/audit-logs', requireRole('SUPER_ADMIN'), operationsController.auditLogs);
router.get('/reports/registrations.csv', financeOnly, operationsController.report);
router.get('/registrations', managersOnly, operationsController.registrations);
router.get('/receipts', financeOnly, operationsController.receipts);
router.get('/matches', managersOnly, operationsController.matches);
router.get('/disputes', managersOnly, (req, res, next) => { req.query.status = 'DISPUTED'; return operationsController.matches(req, res, next); });
router.get('/refunds', financeOnly, financeController.index);
router.use(managersOnly);
router.get('/', adminController.dashboard);
router.get('/games', gameController.index);
router.get('/games/new', gameController.newGame);
router.post('/games', imageUpload.single('image'), gameController.create);
router.get('/games/:id/edit', gameController.edit);
router.post('/games/:id', imageUpload.single('image'), gameController.update);
router.post('/games/:id/toggle', gameController.toggle);
router.get('/tournaments', tournamentController.index);
router.get('/tournaments/new', tournamentController.newTournament);
router.post('/tournaments', imageUpload.single('image'), tournamentController.create);
router.get('/tournaments/:id/competition', tournamentController.competition);
router.get('/tournaments/:id/operator', physicalController.operator);
router.post('/tournaments/:id/draw', physicalController.generateDraw);
router.post('/tournaments/:id/rulebook', physicalController.saveRulebook);
router.post('/tournaments/:id/timetable/publish', physicalController.publishTimetable);
router.post('/tournaments/:id/stream', physicalController.saveStream);
router.post('/tournaments/:id/matches', tournamentController.createMatch);
router.get('/tournaments/:id/edit', tournamentController.edit);
router.post('/tournaments/:id', imageUpload.single('image'), tournamentController.update);
router.post('/tournaments/:id/transition', tournamentController.transition);

module.exports = router;
